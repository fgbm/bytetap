/**
 * Источник строк ленты: кольцевой буфер записи или страницы журнала (FR-28, FR-29).
 *
 * Во время записи событие есть всегда, поэтому `FeedBuffer.at` отдаёт его без промахов.
 * В просмотре журнала строки читаются страницами, и событие на месте строки появляется
 * только после загрузки её страницы: `at` возвращает `undefined`, пока страница едет.
 */

export interface FeedSource<T> {
  /** Номер версии: растёт на каждое изменение, по нему пересчитываются строки. */
  readonly version: number;
  /** Сколько событий всего: у журнала — из сводки, без чтения файла. */
  readonly length: number;
  /** Событие по порядку или `undefined`, если его страница ещё не загружена. */
  at(index: number): T | undefined;
  /** Просьба загрузить строки `[start, end)`; буферу записи не нужна. */
  ensure?(start: number, end: number): void;
  /** Длина события в байтах, если источник знает её без чтения файла (журнал). */
  byteLength?(index: number): number | null;
}
